    /** 按关键词模糊匹配城市（空关键词返回全部）。 */
    public static List<PlaceSearch.Result> search(String keyword) {
        List<PlaceSearch.Result> out = new ArrayList<>();
        String kw = keyword == null ? "" : keyword.trim();
        for (String[] row : DATA) {
            String name = row[0];
            boolean hit = kw.isEmpty() || name.contains(kw)
                    || kw.contains(name) || pinyinHit(name, kw);
            if (!hit) {
                continue;
            }
            // 此处存的是 BD-09：先转 GCJ-02 再交给统一的 Result（Result 约定为 WGS-84）
            double lonBd = Double.parseDouble(row[1]);
            double latBd = Double.parseDouble(row[2]);
            double[] gcj = GeoTransform.bd09ToGcj02(lonBd, latBd);
            double[] wgs = GeoTransform.gcj02ToWgs84(gcj[0], gcj[1]);
            out.add(new PlaceSearch.Result(name + "（城市中心）", "内置离线库",
                    wgs[0], wgs[1], "内置"));
        }
        return out;
    }

    /** 极简拼音首字母匹配：覆盖常见输入（如 cz -> 常州、bj -> 北京）。 */
    private static boolean pinyinHit(String name, String kw) {
        String py = PINYIN.get(name);
        if (py == null || kw.isEmpty()) {
            return false;
        }
        String k = kw.toLowerCase(Locale.CHINA);
        return py.startsWith(k);
    }

